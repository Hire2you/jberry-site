// One-off generator: fetches ONS ultra-generalised (500m) boundaries and writes
// lib/areaMapPaths.ts with projected SVG paths for the AreaMap component.
// Usage: npm i --no-save @turf/turf && node scripts/generate-area-map.mjs (then `npm prune`)
import { writeFileSync } from 'node:fs';
import * as turf from '@turf/turf';

const CTYUA_URL =
  'https://services1.arcgis.com/ESMARspQHYMw9BZ9/arcgis/rest/services/Counties_and_Unitary_Authorities_December_2024_Boundaries_UK_BUC/FeatureServer/0/query';
const REGION_URL =
  'https://services1.arcgis.com/ESMARspQHYMw9BZ9/arcgis/rest/services/Regions_December_2024_Boundaries_EN_BUC/FeatureServer/0/query';

const COUNTIES = [
  'Essex', 'Thurrock', 'Southend-on-Sea',
  'Kent', 'Medway',
  'Hertfordshire',
  // context only
  'Surrey', 'East Sussex', 'West Sussex', 'Buckinghamshire', 'Cambridgeshire',
  'Suffolk', 'Bedford', 'Central Bedfordshire', 'Luton', 'Milton Keynes',
  'Windsor and Maidenhead', 'Slough', 'Bracknell Forest', 'Wokingham', 'Reading', 'Hampshire', 'Oxfordshire',
];

async function fetchGeojson(url, where, outFields) {
  const params = new URLSearchParams({ where, outFields, f: 'geojson', outSR: '4326' });
  const res = await fetch(`${url}?${params}`);
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${where}`);
  const json = await res.json();
  if (json.error) throw new Error(JSON.stringify(json.error));
  return json;
}

const nameList = COUNTIES.map((n) => `'${n.replace(/'/g, "''")}'`).join(',');
const counties = await fetchGeojson(CTYUA_URL, `CTYUA24NM IN (${nameList})`, 'CTYUA24NM');
const londonFc = await fetchGeojson(REGION_URL, `RGN24NM = 'London'`, 'RGN24NM');

console.log('counties fetched:', counties.features.map((f) => f.properties.CTYUA24NM).sort().join(', '));
console.log('regions fetched:', londonFc.features.map((f) => f.properties.RGN24NM).join(', '));

const byName = (name) => {
  const f = counties.features.find((x) => x.properties.CTYUA24NM === name);
  if (!f) throw new Error(`missing county: ${name}`);
  return f;
};
const unionOf = (...names) => turf.union(turf.featureCollection(names.map(byName)));

const essex = unionOf('Essex', 'Thurrock', 'Southend-on-Sea');
const kent = unionOf('Kent', 'Medway');
const herts = byName('Hertfordshire');
const london = londonFc.features[0];
const contextNames = COUNTIES.filter((n) => !['Essex', 'Thurrock', 'Southend-on-Sea', 'Kent', 'Medway', 'Hertfordshire'].includes(n));
const context = contextNames.map(byName);

// --- projection: equirectangular, fitted to the highlight regions + padding ---
const W = 600, H = 520, PAD = 14;
const COS = Math.cos((51.5 * Math.PI) / 180);
const raw = ([lon, lat]) => [lon * COS, -lat];

const fitFc = turf.featureCollection([essex, kent, herts, london]);
const [minLon, minLat, maxLon, maxLat] = turf.bbox(fitFc);
const [rx0, ry1] = raw([minLon, minLat]);
const [rx1, ry0] = raw([maxLon, maxLat]);
const scale = Math.min((W - 2 * PAD) / (rx1 - rx0), (H - 2 * PAD) / (ry1 - ry0));
const ox = (W - (rx1 - rx0) * scale) / 2;
const oy = (H - (ry1 - ry0) * scale) / 2;
const project = ([lon, lat]) => {
  const [rx, ry] = raw([lon, lat]);
  return [(rx - rx0) * scale + ox, (ry - ry0) * scale + oy];
};

const r1 = (n) => Math.round(n * 10) / 10;
function ringToPath(ring) {
  return ring.map(([lon, lat], i) => {
    const [x, y] = project([lon, lat]);
    return `${i === 0 ? 'M' : 'L'}${r1(x)} ${r1(y)}`;
  }).join('') + 'Z';
}
function featureToPath(feature) {
  const g = feature.geometry;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  return polys
    .flatMap((rings) => rings)
    .filter((ring) => ring.length > 8) // drop tiny generalisation slivers/islets
    .map(ringToPath)
    .join('');
}

const markers = {
  hq: project([0.15, 51.814]), // Sawbridgeworth
  london: project([-0.1276, 51.5072]), // Charing Cross
  essex: project([0.4685, 51.7361]), // Chelmsford
  kent: project([0.5227, 51.2704]), // Maidstone
};
const roundPt = ([x, y]) => ({ x: r1(x), y: r1(y) });

const out = `// Generated by scripts/generate-area-map.mjs — do not edit by hand.
// Source: ONS Counties and Unitary Authorities / Regions (December 2024), ultra generalised (500m),
// via the Open Geography portal. Contains OS data © Crown copyright and database right 2024.
export const VIEW = { w: ${W}, h: ${H} };

export const regionPaths = {
  london: '${featureToPath(london)}',
  essex: '${featureToPath(essex)}',
  kent: '${featureToPath(kent)}',
  herts: '${featureToPath(herts)}',
};

export const contextPath = '${context.map(featureToPath).join('')}';

export const markerPoints = {
  hq: ${JSON.stringify(roundPt(markers.hq))},
  London: ${JSON.stringify(roundPt(markers.london))},
  Essex: ${JSON.stringify(roundPt(markers.essex))},
  Kent: ${JSON.stringify(roundPt(markers.kent))},
};
`;

writeFileSync(new URL('../lib/areaMapPaths.ts', import.meta.url), out);
console.log('wrote lib/areaMapPaths.ts');
console.log('markers:', JSON.stringify({
  hq: roundPt(markers.hq), london: roundPt(markers.london), essex: roundPt(markers.essex), kent: roundPt(markers.kent),
}));
